/*============================ pass/fail bookkeeping =================================*/
static int g_pass = 0, g_fail = 0;
#define CHECK(c, m) do { if (c) g_pass++; else { g_fail++; printf("  FAIL: %s (line %d)\n", (m), __LINE__); } } while (0)

/*============================ real pixel readback ====================================*/
/* u8g2_ll_hvline_vertical_top_lsb's own layout (Drivers/u8g2_csrc/u8g2_ll_hvline.c):
 * bytes are vertical, LSB = top pixel of each 8-row band; byte offset for
 * (x,y) is (y>>3)*tile_width*8 + x, bit index (y&7). Read directly out of
 * the REAL u8g2 tile buffer -- not re-derived/estimated. */
static int get_pixel(u8g2_t *u, int x, int y)
{
    if (x < 0 || x >= DISP_W || y < 0 || y >= DISP_H) return 0;
    uint8_t *buf = u8g2_GetBufferPtr(u);
    int tile_width = (int)u8g2_GetBufferTileWidth(u);
    int band = y >> 3;
    long byte_off = (long)band * tile_width * 8 + x;
    int bit = y & 7;
    return (buf[byte_off] >> bit) & 1;
}

static void render(void (*draw_fn)(void))
{
    u8g2_ClearBuffer(&m1_u8g2);
    u8g2_FirstPage(&m1_u8g2);
    do {
        draw_fn();
    } while (u8g2_NextPage(&m1_u8g2));
}

static void snapshot(uint8_t grid[DISP_H][DISP_W])
{
    for (int y = 0; y < DISP_H; y++)
        for (int x = 0; x < DISP_W; x++)
            grid[y][x] = (uint8_t)get_pixel(&m1_u8g2, x, y);
}

/* Writes a 4x nearest-neighbor upscaled P6 (binary PPM) of the CURRENT real
 * u8g2 buffer. "on" pixel (TXT color, lit) -> black; "off" -> white --
 * matches how the physical reflective LCD's dark-on-light text reads. */
static void dump_ppm(const char *name)
{
    char path[512];
    snprintf(path, sizeof(path), "%s/%s.ppm", OUT_DIR, name);
    FILE *f = fopen(path, "wb");
    if (!f) { fprintf(stderr, "could not open %s for writing\n", path); return; }
    const int scale = 4;
    fprintf(f, "P6\n%d %d\n255\n", DISP_W * scale, DISP_H * scale);
    for (int y = 0; y < DISP_H; y++) {
        unsigned char row[DISP_W * scale * 3];
        for (int x = 0; x < DISP_W; x++) {
            int on = get_pixel(&m1_u8g2, x, y);
            unsigned char v = on ? 0 : 255;
            for (int sx = 0; sx < scale; sx++) {
                row[(x * scale + sx) * 3 + 0] = v;
                row[(x * scale + sx) * 3 + 1] = v;
                row[(x * scale + sx) * 3 + 2] = v;
            }
        }
        for (int sy = 0; sy < scale; sy++)
            fwrite(row, 1, sizeof(row), f);
    }
    fclose(f);
    printf("  wrote %s\n", path);
}

/*============================ header-row integrity check ==============================*/
/* Why equality, not "both on": u8g2's framebuffer is 1-bit, so once
 * something is drawn "on" you cannot tell from the final bitmap alone
 * whether that bit came from the header or from something drawn over/near
 * it -- a naive "are both header_grid and row0_grid 'on' here" scan is
 * trivially satisfied by the header's OWN pixels, since the header is drawn
 * identically, first, in every scenario of this screen (with 0 items, with
 * N items, box or no box) -- it would "collide with itself" regardless of
 * whether the real bug is fixed. A hardcoded box rectangle is no better: it
 * goes stale the moment the box geometry changes, and it can accidentally
 * include unrelated content (the app_count==0 scenario also draws a
 * fallback "No applications"/"Auth required..." message below the header,
 * which is not sharable across an app_count==0 vs N>0 comparison).
 *
 * The real invariant that must hold is: HEADER_Y0..HEADER_Y1 (the header's
 * own measured ink rows -- ascent 8 + descent 2 for NFC_FONT_EMPH at
 * baseline 9, i.e. rows 1..11; row 0 included for margin) must be rendered
 * IDENTICALLY regardless of what the rest of the screen draws. So: render
 * once with items (real selection box or plain row-0 text engaged) and
 * once with zero items (pure header + fallback text, which never reaches
 * this row range), then require the two renders' pixels to be PIXEL-EQUAL
 * across HEADER_Y0..HEADER_Y1, full display width. Any difference there
 * proves something other than the header painted into the header's own
 * rows -- which is exactly what the original, hardware-reported bug did
 * (the old row-0 box extended up into rows 3..13, overlapping row 1..11). */
#define HEADER_Y0 0
#define HEADER_Y1 11

static int header_row_diff_scan(uint8_t header_grid[DISP_H][DISP_W], uint8_t row0_grid[DISP_H][DISP_W],
                                 int coords_out[][2], int max_coords)
{
    int n = 0;
    for (int y = HEADER_Y0; y <= HEADER_Y1; y++) {
        for (int x = 0; x < DISP_W; x++) {
            if (header_grid[y][x] != row0_grid[y][x]) {
                if (n < max_coords) { coords_out[n][0] = x; coords_out[n][1] = y; }
                n++;
            }
        }
    }
    return n;
}

/*============================ scenario builders =======================================*/

static void setup_apps_scenario(uint8_t app_count, uint8_t sel, uint8_t scroll)
{
    nfc_ctx_clear_desfire();
    nfc_run_ctx_t *ctx = nfc_ctx_get();
    mf_desfire_deep_t *deep = &ctx->desfire_deep;
    deep->app_count = app_count;
    deep->apps_protected = false;
    for (uint8_t i = 0; i < app_count && i < MF_DESFIRE_DEEP_MAX_APPS; i++) {
        deep->apps[i].id.id[0] = (uint8_t)(0x10 + i);
        deep->apps[i].id.id[1] = (uint8_t)(0x2A + i);
        deep->apps[i].id.id[2] = (uint8_t)(0xF0 + i);
        deep->apps[i].select_ok = (i != 1); /* one "(no select)" app to exercise that text path */
    }
    s_desf_app_sel = sel;
    s_desf_apps_scroll = scroll;
}

