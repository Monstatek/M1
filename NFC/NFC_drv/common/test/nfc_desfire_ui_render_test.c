    render(nfc_desfire_apps_draw);
    dump_ppm("04_apps_4apps_last_selected");
    snapshot(row0_grid);
    report_and_check_header_integrity("Applications (4 apps, last selected)", header_grid, row0_grid);

    printf("== 5. Files: 1 file, selected ==\n");
    setup_files_scenario(1, 0, 0);
    render(nfc_desfire_files_draw);
    dump_ppm("05_files_1file_selected");
    snapshot(row0_grid);
    setup_files_scenario(0, 0, 0);
    render(nfc_desfire_files_draw);
