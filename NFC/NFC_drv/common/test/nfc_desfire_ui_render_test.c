/*============================ collision reporting =====================================*/
/* Works uniformly whether row 0 holds the selection box or plain unselected
 * text -- header_row_diff_scan() only asks "did the header's own rows
 * change from the pure-header reference render", which is a meaningful,
 * non-trivial question in both cases (a plain row-0 label bleeding upward
 * into the header would fail this exactly as a box would). */
static void report_and_check_header_integrity(const char *screen_name,
                                               uint8_t header_grid[DISP_H][DISP_W], uint8_t row0_grid[DISP_H][DISP_W])
{
    int coords[512][2];
    int n = header_row_diff_scan(header_grid, row0_grid, coords, 512);
    if (n == 0) {
        printf("  [%s] real-render scan: header rows (y=%d..%d) rendered IDENTICALLY to the "
               "pure-header reference -- no interference.\n", screen_name, HEADER_Y0, HEADER_Y1);
    } else {
        printf("  [%s] real-render scan: %d pixel(s) in the header's own rows (y=%d..%d) differ "
               "from the pure-header reference render:", screen_name, n, HEADER_Y0, HEADER_Y1);
        int shown = n < 512 ? n : 512;
        for (int i = 0; i < shown; i++) printf(" (%d,%d)", coords[i][0], coords[i][1]);
        printf("\n");
    }
    char msg[160];
    snprintf(msg, sizeof(msg),
             "%s: header rows (y=%d..%d) must render identically regardless of row-0 content "
             "(box or plain text)", screen_name, HEADER_Y0, HEADER_Y1);
    CHECK(n == 0, msg);
}

